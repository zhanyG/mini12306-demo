    public List<Train> searchTrains(String start, String end, String date) {
        boolean hasStart = start != null && !start.isBlank();
        boolean hasEnd = end != null && !end.isBlank();
        boolean hasDate = date != null && !date.isBlank();

        if (!hasDate) {
            if (hasStart && hasEnd) {
                return trainRepository.findByStartStationContainingAndEndStationContaining(start, end);
            }
            if (hasStart) {
                return trainRepository.findByStartStationContaining(start);
            }
            if (hasEnd) {
                return trainRepository.findByEndStationContaining(end);
            }
            return trainRepository.findAll();
        }

        LocalDate queryDate;
        try {
            queryDate = LocalDate.parse(date);
        } catch (Exception ex) {
            throw new RuntimeException("date 参数格式错误，应为 yyyy-MM-dd");
        }

        LocalDateTime departureStart = queryDate.atStartOfDay();
        LocalDateTime departureEnd = queryDate.plusDays(1).atStartOfDay().minusNanos(1);

        if (hasStart && hasEnd) {
            return trainRepository.findByStartStationContainingAndEndStationContainingAndDepartureTimeBetween(
                    start, end, departureStart, departureEnd);
        }
        if (hasStart) {
            return trainRepository.findByStartStationContainingAndDepartureTimeBetween(
                    start, departureStart, departureEnd);
        }
        if (hasEnd) {
            return trainRepository.findByEndStationContainingAndDepartureTimeBetween(
                    end, departureStart, departureEnd);
        }
        return trainRepository.findByDepartureTimeBetween(departureStart, departureEnd);
    }

